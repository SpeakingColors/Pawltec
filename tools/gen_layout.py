#!/usr/bin/env python3
"""Generate src/editor/Layout.h from docs/mockup/layout.json (made by tools/dump_layout.py from the
approved mockup). Every position, size, label and tooltip of the native window comes from the mockup
this way. The mockup page has a preview rig under the knobs ("not part of the plugin"); the real
window leaves it out, so everything below it moves up. Run from the repo root."""
import json
d = json.load(open('docs/mockup/layout.json'))
RIG = d['rig'][3]  # 52
H = 640 - RIG
# The mockup was a web preview; these few tips describe the web preview rig, so they are reworded for the plugin.
SUBS = [(' Preview only uses a simple model.', ''),
        ('Live spectrum of the preview sound.', 'Live spectrum of the sound going through the plugin.'),
        ('Try: play pink noise and watch the curve shape it.', 'Try: play pink noise through it and watch the curve shape it.')]
def q(s):
    for a, b in SUBS: s = s.replace(a, b)
    return qq(s)
def qq(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def f(v):
    t = '%g' % v
    if 'e' in t: t = '%.4f' % v
    return t + ('' if '.' in t else '.0') + 'f'
def rc(r): return '{ ' + ', '.join(f(v) for v in r) + ' }'
def up(r): return [r[0], r[1] - RIG, r[2], r[3]]
cheekL = list(d['cheekL']); cheekL[3] = H
cheekR = list(d['cheekR']); cheekR[3] = H
meters = list(d['meters']); meters[3] -= RIG
o = []
o.append('// GENERATED by tools/gen_layout.py from docs/mockup/layout.json. Do not edit by hand.')
o.append('#pragma once')
o.append('namespace layout {')
o.append('struct Rc { float x, y, w, h; };')
o.append('constexpr int W = 1200, H = %d;' % H)
for k, r in [('cheekL', cheekL), ('cheekR', cheekR), ('hdr', d['hdr']), ('disp', d['disp']), ('knobs', d['knobs']), ('meters', meters),
             ('foot', up(d['foot'])), ('logo', d['logo']), ('name', d['name']), ('s87', d['s87']), ('pPrev', d['pPrev']), ('pName', d['pName']),
             ('pNext', d['pNext']), ('pSave', d['pSave']), ('bBypass', d['bBypass']), ('bGuide', d['bGuide']), ('bSettings', d['bSettings']),
             ('bAbout', d['bAbout']), ('cvResp', d['cvResp']), ('cvSpec', d['cvSpec']), ('cvMet', d['cvMet']), ('pkIn', d['pkIn']), ('pkOut', d['pkOut']),
             ('winsz', up(d['winsz'])), ('footText', up(d['footTexts'][0]['r'])), ('brand', d['brand'])]:
    o.append('constexpr Rc %s = %s;' % (k, rc(r)))
o.append('')
o.append('// Tooltips of the plain controls (the knob and group tips are below).')
for k in ['cheekL', 'brand', 'pPrev', 'pName', 'pNext', 'pSave', 'bBypass', 'bGuide', 'bSettings', 'bAbout', 'cvResp', 'cvSpec', 'cvMet']:
    o.append('constexpr const char* tip_%s = %s;' % (k, q(d['tips'][k])))
o.append('')
o.append('struct Leg { const char* text; Rc r; const char* color; };  // color: ink, g, pink, y, b, accent or dim')
o.append('struct Cap { const char* title; Rc titleR; int nLeg; Leg leg[5]; };')
caps = []
for c in d['caps']:
    leg = []
    for l in c['leg']:
        col = l['color'].replace('var(--', '').replace(')', '') or 'dim'
        leg.append('{ %s, %s, %s }' % (q(l['t']), rc(l['r']), q(col)))
    while len(leg) < 5: leg.append('{ "", { 0, 0, 0, 0 }, "dim" }')
    caps.append('{ %s, %s, %d, { %s } }' % (q(c['title']), rc(c['titleR']), len(c['leg']), ', '.join(leg)))
o.append('constexpr Cap caps[2] = {\n    ' + ',\n    '.join(caps) + ' };')
o.append('struct Txt { const char* text; Rc r; };')
o.append('constexpr Txt meterCaps[2] = { ' + ', '.join('{ %s, %s }' % (q(m['t']), rc(m['r'])) for m in d['mcaps']) + ' };')
o.append('')
o.append('struct Group { const char* title; Rc r; Rc titleR; const char* tip; };')
o.append('constexpr Group groups[4] = {\n    ' + ',\n    '.join('{ %s, %s, %s, %s }' % (q(g['title']), rc(g['r']), rc(g['titleR']), q(g['tip'])) for g in d['groups']) + ' };')
o.append('struct Cell { const char* id; int group; const char* label; Rc labelR; Rc knob; Rc value; const char* tip; };')
ids = ['lowF', 'lowB', 'lowA', 'hiF', 'hiB', 'bw', 'attF', 'hiA', 'tube', 'out']
cells = []
n = 0
for gi, g in enumerate(d['groups']):
    for c in g['cells']:
        v = c['valR']; k = c['knobR']
        cells.append('{ %s, %d, %s, %s, %s, %s, %s }' % (q(ids[n]), gi, q(c['lab']), rc(c['labR']), rc(k), rc([k[0], v[1], k[2], v[3]]), q(c['tip'])))
        n += 1
assert n == 10
o.append('constexpr Cell cells[10] = {\n    ' + ',\n    '.join(cells) + ' };')
o.append('} // namespace layout')
open('src/editor/Layout.h', 'w').write('\n'.join(o) + '\n')
print('ok, window 1200 x %d' % H)
